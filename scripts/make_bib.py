"""
make_bib.py
===========
Build paper/refs.bib from literature/literature_table.csv.

Why: the CSV is the ONE place where references are recorded (with how each was
verified). Generating the .bib from it means the paper can never cite something
that is not in the table.

Run from the project folder:   python scripts/make_bib.py
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TABLE = os.path.join(ROOT, "literature", "literature_table.csv")
BIB = os.path.join(ROOT, "paper", "refs.bib")


def latex_safe(text):
    """Escape the few characters that break BibTeX/LaTeX."""
    for bad, good in [("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#")]:
        text = text.replace(bad, good)
    return text


def entry_for(row):
    """Turn one CSV row into one BibTeX entry (article, book or misc)."""
    authors = " and ".join(a.strip() for a in row["authors"].split(";"))
    if ";" not in row["authors"] and "." not in row["authors"]:
        authors = "{" + authors + "}"                    # corporate author, e.g. {AIP Publishing}
    title = "{" + latex_safe(row["title"]) + "}"          # double braces keep capitals
    vp = row["volume_pages"]
    link = row["doi_or_url"]
    fields = {"author": authors, "title": title, "year": row["year"]}

    if vp == "book":
        kind = "book"
        fields["publisher"] = latex_safe(row["venue"])
        if link.startswith("ISBN"):
            fields["isbn"] = link.replace("ISBN", "").strip()
    elif vp in ("web page",) or row["venue"].startswith("arXiv"):
        kind = "misc"
        fields["howpublished"] = latex_safe(row["venue"])
        if link.startswith("http"):
            fields["url"] = link
        fields["note"] = "Accessed 27 October 2026" if vp == "web page" else latex_safe(vp)
    else:
        kind = "article"
        fields["journal"] = latex_safe(row["venue"])
        # volume_pages looks like 23(4):1204-1225 or 17:031504
        if ":" in vp:
            vol, pages = vp.split(":", 1)
            if "(" in vol:                       # e.g. "23(4)" -> volume 23, number 4
                vol, number = vol.rstrip(")").split("(", 1)
                fields["number"] = number
            fields["volume"] = vol
            fields["pages"] = pages.replace("-", "--")
        else:
            fields["note"] = latex_safe(vp)
        if link.startswith("https://doi.org/"):
            fields["doi"] = link.replace("https://doi.org/", "")
        elif link.startswith("http"):
            fields["url"] = link

    body = ",\n".join(f"  {name} = {{{value}}}" for name, value in fields.items())
    return f"@{kind}{{{row['key']},\n{body}\n}}\n"


def main():
    with open(TABLE, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    os.makedirs(os.path.dirname(BIB), exist_ok=True)
    with open(BIB, "w", encoding="utf-8") as fh:
        fh.write("% AUTO-GENERATED by scripts/make_bib.py from literature/literature_table.csv\n")
        fh.write("% Edit the CSV, not this file.\n\n")
        for row in rows:
            fh.write(entry_for(row) + "\n")
    print(f"Wrote {len(rows)} entries to paper/refs.bib")


if __name__ == "__main__":
    main()
